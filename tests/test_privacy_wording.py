"""Privacy, network and version wording matches what ORBIT actually does.

ORBIT's own network use is the optional GitHub release check and SMTP email that the user has
configured and enabled; there is no telemetry. Synthetic and offline.
"""
import re
from pathlib import Path

import pytest

from orbit.config import FOOTER, VERSION
from orbit.tui.screens.help import HELP_TEXT

ROOT = Path(__file__).resolve().parent.parent
CURRENT_DOCS = ["README.md", "SECURITY.md", "LEGAL.md", "CONTRIBUTING.md", "AGENTS.md",
                "docs/PRIVACY.md", "docs/INSTALL.md", "docs/VALUE.md", "docs/index.html",
                ".github/ISSUE_TEMPLATE/bug_report.yml", ".github/ISSUE_TEMPLATE/feature_request.yml"]

# Blanket claims that SMTP delivery of the report makes untrue.
FORBIDDEN = [
    "no data transmitted", "no data is transmitted", "no data ever leaves", "no data leaves",
    "zero outbound", "makes no outbound", "makes **no outbound", "does not make network connections",
    "itself does not make network", "bytes sent externally", "100% client-side",
    "100% client side", "never leave it", "never leaves your machine", "without your data ever",
    "does not check for updates by contacting", "no update checking", "no update pings",
    "everything orbit does happens on your machine",
    # SMTP may reach a hosted provider or external recipients, so these absolutes are untrue
    "never to the author or any other third party",
    "sends nothing to the author or any other third party",
    "any other third party, and no telemetry",
    "no data is transmitted to the author or any third party",
    "to your own smtp server", "via your own mail server", "only to the mail server",
]


def _text(path: str) -> str:
    raw = (ROOT / path).read_text(encoding="utf-8")
    return " ".join(re.sub(r"<[^>]+>", "", raw).replace("**", "").lower().split())


@pytest.mark.parametrize("doc", CURRENT_DOCS)
def test_current_documents_make_no_blanket_no_transmission_claim(doc):
    text = _text(doc)
    assert [p for p in FORBIDDEN if p in text] == []


def test_help_text_and_footer_make_no_blanket_claim():
    for text in (HELP_TEXT.lower(), FOOTER.lower()):
        assert [p for p in FORBIDDEN if p in " ".join(text.split())] == []


def test_footer_discloses_smtp_and_no_telemetry():
    assert FOOTER.startswith(f"Generated by ORBIT v{VERSION}")
    assert "no telemetry" in FOOTER.lower() and "SMTP" in FOOTER


@pytest.mark.parametrize("doc", ["README.md", "LEGAL.md", "docs/PRIVACY.md", "docs/index.html"])
def test_public_privacy_statements_name_both_requests_and_no_telemetry(doc):
    text = _text(doc)
    assert "github release check" in text and "smtp" in text and "telemetry" in text


@pytest.mark.parametrize("doc", ["LEGAL.md", "docs/PRIVACY.md"])
def test_smtp_destinations_are_user_chosen_and_may_be_third_party(doc):
    text = _text(doc)
    assert "smtp server" in text and "hosted" in text
    assert "recipients" in text and ("configure" in text or "you chose" in text)
    assert "automatically" in text and "author" in text and "no telemetry" in text


def test_privacy_states_the_guarantee_as_no_automatic_author_submission():
    text = _text("docs/PRIVACY.md")
    assert "never sends anything to the author automatically" in text
    assert "no automatic submission of anything to the author" in text
    assert "user-configured smtp sends the selected report data" in text
    legal = _text("LEGAL.md")
    assert "does not automatically submit anything to the author" in legal
    assert "no telemetry or analytics are collected" in legal


@pytest.mark.parametrize("doc", ["README.md", "docs/INSTALL.md", "docs/PRIVACY.md", "SECURITY.md"])
def test_docs_never_tell_users_to_edit_package_data(doc):
    text = (ROOT / doc).read_text(encoding="utf-8")
    assert "orbit/data/tool_hashes.json" not in text


@pytest.mark.parametrize("doc", ["README.md", "docs/INSTALL.md"])
def test_install_docs_point_at_the_installed_command_and_orbit_home(doc):
    text = (ROOT / doc).read_text(encoding="utf-8")
    assert "orbit-generate-hashes" in text
    assert "~/.orbit/tool_hashes.json" in text and "ORBIT_HOME" in text
    assert "not imported" in text or "never imports" in text  # legacy baselines stay untrusted


def test_help_points_at_the_baseline_command():
    assert "orbit-generate-hashes" in HELP_TEXT and "~/.orbit/tool_hashes.json" in HELP_TEXT


def test_help_text_names_both_requests():
    text = HELP_TEXT.lower()
    assert "github" in text and "smtp" in text and "telemetry" in text


def test_privacy_statement_separates_the_four_kinds_of_activity():
    text = _text("docs/PRIVACY.md")
    for needle in ("optional github release check", "smtp email (only if you configure and enable it)",
                   "network activity by launched tools and installers", "no telemetry, analytics",
                   "assessment details", "pdf summary report", "test message",
                   "email results when complete"):
        assert needle in text, needle


def test_current_product_references_use_the_current_version():
    assert f'Footer: "Generated by ORBIT v{VERSION} —' in (ROOT / "README.md").read_text(encoding="utf-8")
    assert f"describes ORBIT v{VERSION}" in (ROOT / "docs/PRIVACY.md").read_text(encoding="utf-8")
    bug = (ROOT / ".github/ISSUE_TEMPLATE/bug_report.yml").read_text(encoding="utf-8")
    assert f"v{VERSION}" in bug
    for doc in ("README.md", "docs/PRIVACY.md", ".github/ISSUE_TEMPLATE/bug_report.yml",
                "docs/index.html"):
        text = (ROOT / doc).read_text(encoding="utf-8")
        assert "v1.0.0" not in text and "version-1.0.0" not in text and "version-1.2.0" not in text, doc


def test_feature_request_template_states_the_real_network_policy():
    text = (ROOT / ".github/ISSUE_TEMPLATE/feature_request.yml").read_text(encoding="utf-8")
    assert "GitHub release check" in text and "SMTP" in text
    assert "No telemetry or analytics" in text

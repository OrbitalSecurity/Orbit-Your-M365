def resource_dir(*parts: str) -> Path:
    """Directory of bundled package data, resolved through importlib.resources.

    The data ships inside the ``orbit`` package (``orbit/data``), so one lookup serves a
    source checkout, an editable install and a wheel install. ORBIT reads it and never writes
    to it. The lookup fails loudly if the package is not on a regular filesystem (for example
    imported from a zip), because the consumers need real paths.
    """
    root = resources.files("orbit")
    for part in parts:
        root = root / part
    if not isinstance(root, Path):
        raise RuntimeError(  # noqa: TRY004 - an environment fault, not a caller's type error
            "ORBIT package data must be installed on a regular filesystem, not imported from an archive")
    return root


